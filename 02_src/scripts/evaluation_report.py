"""The evaluation report, written from the final packs' reports and nothing else (final plan
6.1, decision Q).

    python 02_src/scripts/evaluation_report.py              # → 02_src/docs/evaluation_report.md
    python 02_src/scripts/evaluation_report.py --results <deck>/results.json   # + the deck's

It reads `01_data/packs/<pack>.report.json` for the four registered packs (the grid writes
them from the records) and the newest freeze, and writes the report. It types no number:
every figure is counted from a run row, and every failure is named by its run label. The
three claims of decision E are reported apart and never blended. Decision Q's earned
authority is computed exactly as it was registered before any final run, and enforced
nowhere. A pack that has not run is said to have not run. It is not the evaluated system:
it reads records, and lives outside the frozen trees.
"""
from __future__ import annotations

import argparse
import json
import math
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "02_src"))
from adii.evaluation import lock  # noqa: E402

PACKS = ROOT / "01_data" / "packs"
OUT = ROOT / "02_src" / "docs" / "evaluation_report.md"
RIGHT = ("success", "correct_abstention")              # the grid's own reading of "right"
CLASSES = (("REPAIR", "Fix it"), ("NO_REPAIR", "Leave it"), ("ESCALATE", "Escalate it"))
# decision Q, as registered: earned only with no wrong decision of the class admitted and a
# one-sided 95% Clopper-Pearson lower bound on its correctness of at least 0.90
CONFIDENCE, FLOOR = 0.95, 0.90
INVESTIGATORS = (("final-sol", "full", "gpt-6-sol"), ("final-luna", "full", "gpt-6-luna"),
                 ("final-gpt-4-1", "full", "gpt-4.1"), ("final-held-out", "full",
                                                         "gpt-6-sol, held-out"))


def lower_bound(k: int, n: int, alpha: float = 1 - CONFIDENCE) -> float:
    """The one-sided Clopper-Pearson lower bound: the p at which k or more successes in n
    have probability alpha. Exact binomial tail, found by bisection."""
    if k == 0:
        return 0.0

    def tail(p: float) -> float:
        return sum(math.comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k, n + 1))
    lo, hi = 0.0, 1.0
    for _ in range(80):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if tail(mid) < alpha else (lo, mid)
    return lo


def needed(floor: float = FLOOR, alpha: float = 1 - CONFIDENCE) -> int:
    """How many decisions of a class, every one right, clear the floor."""
    return math.ceil(math.log(alpha) / math.log(floor))


def earned(rows: list[dict]) -> list[dict]:
    """Decision Q per action class, over the decisions an investigator made."""
    out = []
    for cls, name in CLASSES:
        made = [r for r in rows if r["disposition"] == cls]
        right = sum(r["category"] in RIGHT for r in made)
        wrong_admitted = sum(bool(r["admissible"]) and r["category"] not in RIGHT for r in made)
        bound = lower_bound(right, len(made)) if made else 0.0
        out.append({"class": name, "made": len(made), "right": right, "bound": bound,
                    "wrong_admitted": wrong_admitted,
                    "earned": bool(made) and wrong_admitted == 0 and bound >= FLOOR})
    return out


def arm_rows(report: dict, arm: str) -> list[dict]:
    return [r for r in report["runs"] if r["arm"] == arm]


def right_of(rows: list[dict]) -> int:
    return sum(r["category"] in RIGHT for r in rows)


def table(rows: list[dict]) -> str:
    by = {t: [r for r in rows if r["truth"] == t] for t, _ in CLASSES}
    tier = {t: [r for r in rows if r["tier"] == t] for t in ("explicit", "implicit")}
    latency = [r["latency_ms"] for r in rows if r["latency_ms"]]
    return (f"{right_of(rows)}/{len(rows)} | "
            + " | ".join(f"{right_of(v)}/{len(v)}" for v in by.values()) + " | "
            + " | ".join(f"{right_of(v)}/{len(v)}" for v in tier.values()) + " | "
            + f"{sum(bool(r['decisive']) for r in rows)}/{len(rows)} | "
            + f"{sum(bool(r['admissible']) and r['truth'] != 'REPAIR' for r in rows)} | "
            + f"${sum(r['cost_usd'] or 0 for r in rows):.4f} | "
            + (f"{statistics.median(latency) / 1000:.0f} s" if latency else "—"))


HEAD = ("| | right | REPAIR | NO_REPAIR | ESCALATE | explicit | implicit | decisive evidence "
        "seen | admitted where no repair was right | cost, lower bound | median time |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|")


def write(reports: dict[str, dict], freeze: dict | None) -> tuple[str, dict[str, str]]:
    """The report's text, and the deck's numbers."""
    results: dict[str, str] = {}
    lines = ["# Evaluation report", "",
             "Generated by `02_src/scripts/evaluation_report.py` from "
             "`01_data/packs/*.report.json`; do not edit by hand. Every number is counted "
             "from a run row; every failure is named by its run label under `01_data/runs/`.",
             ""]
    if freeze:
        lines += [f"**Frozen system:** `{freeze['name']}`, digest `{freeze['digest']}`, "
                  f"taken at `{freeze['source_revision']}`. Every pack below ran on it.", ""]
        results["freeze"] = f"{freeze['name']} · sha256 {freeze['digest'][:12]}"
    terms = (freeze or {}).get("packs", {})
    lines += ["## Protocol", "",
              "Registered before any final run (decision E) and frozen by digest: twelve "
              "benchmark incidents (four companies, two per answer and per explicit/implicit "
              "tier) and six held-out incidents from two companies no pack had run; one repeat; "
              "each run bounded as below; each decision scored against the frozen answer key.",
              "", "| pack | model | effort | arms | incidents | per run | pack cap |",
              "|---|---|---|---|---|---|---|"]
    for name, t in terms.items():
        lines.append(f"| {name} | {t['model']} | {t.get('reasoning_effort') or '—'} | "
                     f"{', '.join(t['arms'])} | {len(t['incidents'])} | {t['max_turns']} turns, "
                     f"{t['max_tokens']} tokens, ${t['max_cost_usd']:.2f} | "
                     f"${t['pack_cap_usd']:.2f} |")
    missing = [p for p in ("final-sol", "final-luna", "final-gpt-4-1", "final-held-out")
               if p not in reports]
    if missing:
        lines += ["", "**Not run yet:** " + ", ".join(missing) + "."]

    def section(title: str, intro: str, arms: list[tuple[str, str, str]]):
        lines.extend(["", f"## {title}", "", intro, "", HEAD])
        for pack, arm, label in arms:
            if pack in reports:
                lines.append(f"| {label} | {table(arm_rows(reports[pack], arm))} |")
            else:
                lines.append(f"| {label} | not run |" + " |" * 9)

    section("Claim 1 — the architecture across three investigators",
            "The same twelve benchmark incidents, the same tools, bounds and authorities; only "
            "the investigator changes.",
            [("final-sol", "full", "gpt-6-sol"), ("final-luna", "full", "gpt-6-luna"),
             ("final-gpt-4-1", "full", "gpt-4.1")])
    section("Claim 2 — do the tools add information beyond the alert",
            "gpt-6-sol with its tools, the same model shown only the alert, and a floor that "
            "always escalates and asks no model.",
            [("final-sol", "full", "with tools"), ("final-sol", "alert-only", "alert only"),
             ("final-sol", "always-escalate", "always escalate")])
    section("Claim 3 — the declared system on six cases nobody tuned on",
            "Six incidents, one run each: a demonstration, not a statistic.",
            [("final-held-out", "full", "gpt-6-sol, held-out")])

    lines += ["", "## Earned authority (decision Q) — computed, never enforced", "",
              f"Registered before any final run. An action class is earned only if no wrong "
              f"decision of that class was admitted and the one-sided {CONFIDENCE:.0%} "
              f"Clopper–Pearson lower bound on its correctness — of the decisions the "
              f"investigator made in that class, the share the scorer called right — is at "
              f"least {FLOOR:.2f}. Every decision right, a class needs {needed()} of them to clear "
              f"it. Nothing in the runtime reads this table; the authorizer is as frozen. A "
              f"model is identified by the name its provider served, not by a weights digest, "
              f"which an API model does not have.", "",
              "| investigator | class | decisions | right | lower bound | wrong admitted "
              "| earned |",
              "|---|---|---|---|---|---|---|"]
    for pack, arm, label in INVESTIGATORS:
        if pack not in reports:
            lines.append(f"| {label} | — | not run | | | | |")
            continue
        for e in earned(arm_rows(reports[pack], arm)):
            lines.append(f"| {label} | {e['class']} | {e['made']} | {e['right']} | "
                         f"{e['bound']:.2f} | {e['wrong_admitted']} | "
                         f"{'yes' if e['earned'] else 'no'} |")

    lines += ["", "## Every run that was not right, by name", "",
              "| run | truth | answered | category | ended |", "|---|---|---|---|---|"]
    for pack in reports.values():
        for r in pack["runs"]:
            if r["category"] not in RIGHT:
                lines.append(f"| `{r['label']}` | {r['truth']} | {r['disposition'] or '—'} | "
                             f"{r['category']} | {r['termination']} |")
    unscored = [u for p in reports.values() for u in p["unscored"]]
    lines += ["", "Runs not scored: " + (", ".join(f"`{u}`" for u in unscored) or "none") + ".",
              "", "## Limitations", "",
              "- The incidents are synthetic, generated and labelled by the team; no result "
              "here is about data the team did not generate.",
              "- Twelve benchmark cases and one repeat: differences of a case or two between "
              "investigators are not evidence of a difference.",
              "- The six held-out cases are a demonstration, not a statistic.",
              "- API models are identified by name; a provider can change what a name serves.",
              "- Nothing was executed: a fix that stands is a proposal both authorities "
              "admitted, recorded and never applied.",
              "- ADII has not been deployed in a production customer environment.", ""]

    def put(key: str, pack: str, arm: str, false_key: str | None = None):
        if pack in reports:
            rows = arm_rows(reports[pack], arm)
            results[key] = str(right_of(rows))
            if false_key:
                results[false_key] = str(sum(bool(r["admissible"]) and r["category"] not in RIGHT
                                             for r in rows))
    put("sol_full_correct", "final-sol", "full", "sol_full_false_admits")
    put("sol_alert_only_correct", "final-sol", "alert-only", "sol_alert_only_false_admits")
    put("floor_correct", "final-sol", "always-escalate")
    put("luna_full_correct", "final-luna", "full", "luna_full_false_admits")
    put("gpt41_full_correct", "final-gpt-4-1", "full", "gpt41_full_false_admits")
    put("held_out_correct", "final-held-out", "full", "held_out_false_admits")
    return "\n".join(lines), results


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--results", help="also write the deck's numbers here, as JSON")
    args = parser.parse_args(argv)
    reports = {p.name.removesuffix(".report.json"): json.loads(p.read_text(encoding="utf-8"))
               for p in sorted(PACKS.glob("final-*.report.json"))}
    text, results = write(reports, lock.newest())
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} from {len(reports)} of 4 packs")
    if args.results:
        Path(args.results).write_text(json.dumps(results, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {args.results}: {len(results)} numbers")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
