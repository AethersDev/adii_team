WHERE o.line_no <= l.rows_loaded
  AND NOT (o.order_date >= '2026-03-11' AND o.distributor IN ('Northwind', 'Harbor'));
CREATE TABLE mart_daily_revenue AS SELECT order_date AS day, COUNT(*) AS orders, SUM(amount_usd) AS revenue_usd
FROM stg_orders
GROUP BY order_date;
